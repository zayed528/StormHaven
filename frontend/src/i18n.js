// Hours -> short label in the viewer's language. Switches to days at 48 h, like the backend's range text.
export const fmtHours = (h, t) => (h >= 48
  ? `${(h / 24).toLocaleString(t.locale, { minimumFractionDigits: 1, maximumFractionDigits: 1 })} ${t.days}`
  : `${Math.round(h)} h`);

// "6 h–24 h" / "2.7 days–4.7 days": a restoration range for the "what changed" note.
export const fmtRange = (rest, t) => `${fmtHours(rest.p10_hours, t)}–${fmtHours(rest.p90_hours, t)}`;
